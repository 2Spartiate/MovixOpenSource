#!/usr/bin/env node

/** Compile the browser runtime into a literal string before Hermes bundles it. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(scriptDir, '../src/injection/parental-controls-runtime.ts');
const outputPath = resolve(scriptDir, '../src/injection/parental-runtime-source.ts');
const source = readFileSync(sourcePath, 'utf8');
const { outputText, diagnostics } = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  reportDiagnostics: true,
});
if (diagnostics?.length) {
  throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: name => name,
    getCurrentDirectory: () => process.cwd(),
    getNewLine: () => '\n',
  }));
}
const browserScript = `(() => {\nconst exports = {};\n${outputText}\ninstallParentalControlsRuntime();\n})();\ntrue;`;
// Catch accidental imports or runtime-only dependencies in the browser script.
new Function(browserScript);
const generated = `/** Generated by scripts/build-parental-injection.js. Do not edit. */\nexport const PARENTAL_RUNTIME_SOURCE = ${JSON.stringify(browserScript)};\n`;
let current = '';
try { current = readFileSync(outputPath, 'utf8'); } catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}
if (process.argv.includes('--check')) {
  if (current !== generated) throw new Error(`Parental injection is stale: ${outputPath}`);
} else if (current !== generated) writeFileSync(outputPath, generated, 'utf8');
console.log(`[parental-injection] ${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${browserScript.length} bytes`);
